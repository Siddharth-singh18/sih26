export function interpolate(text: string, params?: Record<string, string | number>): string {
  if (!params || typeof params !== 'object') return text;
  return Object.entries(params).reduce((acc, [k, v]) => {
    return acc.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
              .replace(new RegExp(`\\{\\{${k}\\}\\}`, 'g'), String(v));
  }, text);
}

export function translateWithFallback(
  key: string,
  targetLanguage: string,
  paramsOrFallback?: string | Record<string, string | number>,
  fallbackOverride?: string
): { text: string; isFallback: boolean; resolvedLanguage: string } {
  const params = typeof paramsOrFallback === 'object' ? paramsOrFallback : undefined;
  const fallback = typeof paramsOrFallback === 'string' ? paramsOrFallback : fallbackOverride;

  const resource = GLOBAL_DICTIONARY[key];
  if (!resource) {
    const raw = fallback || key;
    return {
      text: fallbackOverride || key,
      text: interpolate(raw, params),
      isFallback: true,
      resolvedLanguage: 'en-IN'
    };
  }

  // 1. Exact match
  if (resource[targetLanguage]) {
    return {
      text: resource[targetLanguage],
      text: interpolate(resource[targetLanguage], params),
      isFallback: false,
      resolvedLanguage: targetLanguage
    };
  }

  // 2. Short prefix match (e.g. 'ta' for 'ta-IN')
  const shortCode = targetLanguage.split('-')[0];
  if (resource[shortCode]) {
    return {
      text: resource[shortCode],
      text: interpolate(resource[shortCode], params),
      isFallback: false,
      resolvedLanguage: shortCode
    };
  }

  // 3. Fallback to English
  const englishFallback = resource['en-IN'] || resource['en'] || fallbackOverride || key;
  const englishFallback = resource['en-IN'] || resource['en'] || fallback || key;
  return {
    text: englishFallback,
    text: interpolate(englishFallback, params),
    isFallback: targetLanguage !== 'en-IN' && targetLanguage !== 'en',
    resolvedLanguage: 'en-IN'
  };
}
